/** Best-effort simplified to Traditional conversion for zh-TW. */
export function toTraditional(text: string): string {
  let converted = text;
  for (const [zh, tw] of TERMS) {
    converted = converted.split(zh).join(tw);
  }
  let result = '';
  for (const character of converted) {
    result += CHARACTERS[character] ?? character;
  }
  return result;
}
